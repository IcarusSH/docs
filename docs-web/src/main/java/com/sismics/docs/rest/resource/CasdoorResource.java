package com.sismics.docs.rest.resource;

import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.util.Base64;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import com.sismics.docs.core.model.jpa.User;
import com.sismics.docs.core.service.CasdoorService;
import com.sismics.rest.exception.ForbiddenClientException;

import jakarta.json.JsonObject;
import jakarta.ws.rs.GET;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.QueryParam;
import jakarta.ws.rs.core.NewCookie;
import jakarta.ws.rs.core.Response;

/**
 * Casdoor SSO REST resource.
 *
 * Endpoints:
 *   GET /casdoor/login     -> 302 redirect to Casdoor authorization endpoint
 *   GET /casdoor/callback -> handle Casdoor redirect, exchange code, set session cookie,
 *                             redirect browser to Teedy home
 *
 * Both endpoints are public (no auth required); the callback establishes the
 * session by writing the standard auth_token cookie via AuthTokenUtil.
 */
@Path("/casdoor")
public class CasdoorResource extends BaseResource {
    private static final Logger log = LoggerFactory.getLogger(CasdoorResource.class);

    private final CasdoorService casdoorService = new CasdoorService();

    /**
     * Compute the absolute callback URL for the current request.
     */
    private String callbackUri() {
        return AuthTokenUtil.callbackUri(request);
    }

    /**
     * Build the Teedy post-login home URL (root context path).
     */
    private String homeUri() {
        return AuthTokenUtil.homeUri(request);
    }

    /**
     * The default URL to redirect the browser to after a successful SSO login.
     *
     * We try three strategies, in order:
     *   1. The application.mode system property (set by the dev Jetty profile to "dev")
     *   2. Heuristic: if the contextPath looks like the dev default ("/docs-web" or any
     *      "*-web"), assume the AngularJS source lives at /<ctx>/src/ and the build
     *      target at /<ctx>/dist/. In production (WAR deployed with contextPath "/"
     *      or some short path) the app lives at /<ctx>/.
     *
     * Callers should always prefer the return_to URL the frontend passes in, but this
     * fallback at least keeps us from stranding the user on an empty directory listing.
     */
    private String defaultHomeUri() {
        String ctx = request.getContextPath();
        String mode = System.getProperty("application.mode", "");
        if ("dev".equalsIgnoreCase(mode)) {
            return ctx + "/src/";
        }
        // Heuristic fallback: the dev plugin uses contextPath="/docs-web" by default.
        // If we see that path, assume dev layout. Production deploys with WAR at "/"
        // won't match this.
        if ("/docs-web".equals(ctx) || ctx.endsWith("-web")) {
            return ctx + "/src/";
        }
        return ctx + "/";
    }

    /**
     * Generate a random opaque state parameter carrying the user's intended
     * destination URL. We base64-encode "<randomNonce>|<returnTo>" so the
     * returnTo round-trips through Casdoor's state parameter unmodified.
     */
    private static String encodeState(String returnTo) {
        byte[] nonce = new byte[16];
        new SecureRandom().nextBytes(nonce);
        String encodedNonce = Base64.getUrlEncoder().withoutPadding().encodeToString(nonce);
        String payload = encodedNonce + "|" + (returnTo == null ? "" : returnTo);
        return Base64.getUrlEncoder().withoutPadding()
                .encodeToString(payload.getBytes(StandardCharsets.UTF_8));
    }

    /**
     * Decode a state value generated by encodeState. Returns the embedded
     * returnTo URL, or null if the state is malformed.
     */
    private static String decodeState(String state) {
        if (state == null || state.isEmpty()) return null;
        try {
            String payload = new String(Base64.getUrlDecoder().decode(state), StandardCharsets.UTF_8);
            int sep = payload.indexOf('|');
            if (sep < 0) return null;
            // strip the nonce prefix
            String rest = payload.substring(sep + 1);
            return rest.isEmpty() ? null : rest;
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    /**
     * Issue a redirect to the Casdoor authorization endpoint.
     *
     * @param returnTo Path within Teedy the browser should land on after
     *                 successful callback (e.g. "/docs-web/src/#/")
     * @return 302 response
     */
    @GET
    @Path("login")
    public Response login(@QueryParam("return_to") String returnTo) {
        if (!CasdoorService.isEnabled()) {
            throw new ForbiddenClientException();
        }
        String state = encodeState(returnTo);
        String url = casdoorService.getAuthorizationUrl(state, callbackUri());
        return Response.status(Response.Status.FOUND).header("Location", url).build();
    }

    /**
     * Handle the redirect from Casdoor. Exchanges the code for tokens,
     * fetches the user info, finds-or-creates the local user, sets the
     * auth_token cookie, and redirects the browser back to the page the user
     * started from (encoded in the state parameter).
     *
     * @param code Authorization code from Casdoor
     * @param state State value carrying the original return_to URL
     * @return 302 redirect to Teedy home (with auth cookie), or 302 to login
     *         page with ?error=... if anything went wrong
     */
    @GET
    @Path("callback")
    public Response callback(@QueryParam("code") String code,
                              @QueryParam("state") String state) {
        if (!CasdoorService.isEnabled()) {
            throw new ForbiddenClientException();
        }
        if (code == null || code.isEmpty()) {
            log.warn("Casdoor callback missing code");
            return redirectWithError("casdoor_no_code", decodeState(state));
        }

        String returnTo = decodeState(state);

        try {
            // 1. Exchange code for access token
            JsonObject token = casdoorService.exchangeCodeForToken(code, callbackUri());
            String accessToken = token.getString("access_token", null);
            if (accessToken == null || accessToken.isEmpty()) {
                throw new IOException("Casdoor token response missing access_token");
            }

            // 2. Fetch user info via access token
            JsonObject userInfo = casdoorService.fetchUserInfo(accessToken);

            // 3. Find or create local Teedy user
            User user = casdoorService.findOrCreateUser(userInfo);

            // 4. Issue session token + auth cookie. SSO callback has no "remember me",
            //    so longLasted=false (session cookie that dies on browser close).
            NewCookie cookie = AuthTokenUtil.issueCookie(request, user, false);
            log.info("Casdoor login successful for user \"" + user.getUsername() + "\"");
            return Response.status(Response.Status.FOUND)
                    .location(URI.create(returnTo != null ? returnTo : defaultHomeUri()))
                    .cookie(cookie)
                    .build();
        } catch (Exception e) {
            log.error("Casdoor callback failed", e);
            return redirectWithError("casdoor_" + errorTag(e), returnTo);
        }
    }

    private Response redirectWithError(String tag, String returnTo) {
        // Redirect back to the page the user started from with an error flag;
        // the frontend Login.js reads $location.search().error and shows a
        // localized message. If we don't know where the user came from, fall
        // back to the login page.
        String base = returnTo != null ? returnTo : defaultHomeUri();
        // Strip any existing query string on the return URL before adding our error
        int q = base.indexOf('?');
        String baseNoQuery = q >= 0 ? base.substring(0, q) : base;
        // For the login page we can show the error dialog inline; for any
        // other page we still append the error query param so the Login
        // controller (if the user navigates there) can display it.
        return Response.status(Response.Status.FOUND)
                .location(URI.create(baseNoQuery + "?error=" + tag))
                .build();
    }

    /**
     * Map an exception to a short, URL-safe identifier.
     */
    private static String errorTag(Exception e) {
        if (e instanceof IOException) return "io_error";
        if (e instanceof IllegalArgumentException) return "invalid_userinfo";
        return "provision_failed";
    }
}